def build_seed_signatures() -> list[tuple[str, int, str, str, str, str, str]]:
    rows = []
    for item in RAW_CHAEON_SIGNATURES:
        sid = item["id"]
        num = int(sid)
        tags = []
        if sid in REAL_HOT_SIG_IDS:
            tags.append("realhot")
        if sid in NEW_SIG_IDS:
            tags.append("new")
        if sid in HOT_SIG_IDS:
            tags.append("hot")

        if num >= 10000:
            cat = "10000~"
            badge = "👑"
        elif num >= 3000:
            cat = "3000~9999"
            badge = "💎"
        elif num >= 1000:
            cat = "1000~2999"
            badge = "✨"
        else:
            cat = "시그니처"
            badge = "💖"

        clip_url = item.get("clip", "")
        rows.append((item["title"], num, cat, "", badge, clip_url, ",".join(tags)))
    return rows
